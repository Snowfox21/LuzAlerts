/**
 * Диплинк, который пришёл раньше, чем пользователь прошёл онбординг.
 *
 * Сосед, тапнувший ссылку в WhatsApp, — это чаще всего человек, у которого
 * приложения ещё не было: он поставил APK и открыл его этой самой ссылкой.
 * То есть онбординг и диплинк сталкиваются именно в главном сценарии
 * шеринга, а не в редком краевом случае.
 *
 * Раньше ссылка в этот момент просто выбрасывалась, и человек после
 * онбординга попадал на общую карту — без той метки, ради которой пришёл.
 * Здесь она ждёт, пока онбординг закончится.
 *
 * Живёт в памяти модуля, а не в AsyncStorage: ссылка актуальна ровно до
 * конца этого запуска. Сохранять её на диск — значит однажды открыть
 * человеку чужую метку через неделю после установки.
 */
let pending: string | null = null;

/** Запомнить маршрут (уже разобранный путь вида `/r/ABC123`, не сырой URL). */
export const setPendingLink = (route: string): void => {
    pending = route;
};

/** Забрать и сразу очистить — маршрут одноразовый. */
export const takePendingLink = (): string | null => {
    const route = pending;
    pending = null;
    return route;
};
